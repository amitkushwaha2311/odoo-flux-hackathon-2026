# -*- coding: utf-8 -*-
# =============================================================================
# brightloop_core.models.account_move
#
# Extensions to native account.move and account.move.line for Brightloop
# Subscription Invoicing
#
# PHASE 8 SCOPE
# -------------
# - Links native customer invoices (account.move) to source subscriptions
#   and billing periods.
# - Links invoice lines (account.move.line) to subscription contract lines.
# - Maintains strict traceability from recurring invoice lines back to
#   source contracts and plans.
# =============================================================================

import logging
from odoo import api, fields, models

_logger = logging.getLogger(__name__)


class AccountMove(models.Model):
    _inherit = 'account.move'

    subscription_id = fields.Many2one(
        comodel_name='brightloop.subscription',
        string='Subscription Contract',
        readonly=True,
        index=True,
        copy=False,
        help='Brightloop subscription contract that generated this recurring invoice.',
    )

    billing_period_id = fields.Many2one(
        comodel_name='brightloop.billing.period',
        string='Subscription Billing Period',
        readonly=True,
        index=True,
        copy=False,
        help='The discrete billing period covered by this invoice.',
    )

    billing_period_start = fields.Date(
        string='Billing Period Start',
        readonly=True,
        copy=False,
    )

    billing_period_end = fields.Date(
        string='Billing Period End',
        readonly=True,
        copy=False,
    )

    is_subscription_invoice = fields.Boolean(
        string='Is Subscription Invoice',
        default=False,
        readonly=True,
        index=True,
        help='True if this invoice was generated by the Brightloop recurring billing engine.',
    )


class AccountMoveLine(models.Model):
    _inherit = 'account.move.line'

    subscription_id = fields.Many2one(
        comodel_name='brightloop.subscription',
        string='Subscription Contract',
        readonly=True,
        index=True,
        copy=False,
    )

    subscription_line_id = fields.Many2one(
        comodel_name='brightloop.subscription.line',
        string='Subscription Contract Line',
        readonly=True,
        index=True,
        copy=False,
        help='Source subscription contract line represented by this invoice line.',
    )

